// tokens/tokens.json → dist/tokens.css, dist/theme.css, dist/tokens.json.
//
// Two CSS outputs carry the same values in two shapes:
//
//   tokens.css  plain :root variables, for a site with no Tailwind (404games).
//   theme.css   a Tailwind v4 @theme block, for the404labs and 404shop, so
//               bg-red / font-brand / rounded-card / text-display-lg exist as
//               utilities. Import it after `@import "tailwindcss"`.
//
// A site imports one or the other, never both. They can't be one file: a
// Tailwind @theme variable and a :root variable of the same name would have
// to reference each other.
import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, loadTokens, deriveTones } from "./lib.mjs";

const tokens = loadTokens();
const tones = deriveTones(tokens);

const HEADER = "/* Generated by scripts/build-tokens.mjs from tokens/tokens.json — do not edit. */\n";

const cssValue = (token) => {
  const v = token.$value;
  if (Array.isArray(v)) return v.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
  return String(v);
};

/** One `--prefix-name: value;` line per token in a group. */
function declarations(group, prefix) {
  return Object.entries(tokens[group])
    .filter(([key]) => !key.startsWith("$"))
    .map(([key, token]) => `  --${prefix}${key}: ${cssValue(token)};`);
}

// Namespaces Tailwind v4 turns into utilities. The prefixes are Tailwind's,
// and they are also the names all three sites already use in hand-written
// CSS, so adopting this package renames nothing.
const themed = [
  ...declarations("color", "color-"),
  ...declarations("font", "font-"),
  ...declarations("radius", "radius-"),
  ...declarations("container", "container-"),
  ...declarations("spacing", "spacing-"),
  ...declarations("text", "text-"),
  ...declarations("leading", "leading-"),
  ...declarations("tracking", "tracking-"),
];

// Not Tailwind namespaces: these stay plain variables in both outputs.
const plain = [
  ...declarations("border", "border-"),
  ...declarations("motion", "motion-"),
  ...declarations("z", "z-"),
  // Multiplier form of the a11y text-size setting, for sizes that can't be
  // rem (404games' HUD is sized in container-query units). base.css sets it
  // per data-a11y-text value.
  "  --a11y-text-scale: 1;",
];

const indent = (block) => block.replace(/^(?=.)/gm, "  ");

const toneBlock = (tone) =>
  Object.entries(tone)
    .map(([key, value]) => `  --tone-${key}: ${value};`)
    .join("\n");

// Paper is the page default, so every component has a tone to read even
// outside any [data-tone] ancestor.
const toneVars = [
  `:root {\n${toneBlock(tones.paper)}\n}`,
  ...Object.entries(tones).map(([name, tone]) => `[data-tone="${name}"] {\n${toneBlock(tone)}\n}`),
].join("\n\n");

// In @layer base so a site's own utility or component class still wins.
const toneSurface = `@layer base {\n  [data-tone] {\n    background-color: var(--tone-bg);\n    color: var(--tone-fg);\n  }\n}`;

// Every variable is declared inside @layer theme — the layer Tailwind puts
// its own @theme output in. That is load-bearing, not tidiness: base.css
// overrides some of these from @layer base (the dyslexia font swaps
// --font-*, the text-size setting sets --a11y-text-scale), and a layered
// rule can never outrank an unlayered one, whatever its specificity. Left
// unlayered, the tokens silently defeat the accessibility panel.
const layered = (...blocks) => `@layer theme {\n${blocks.map(indent).join("\n\n")}\n}`;

// The plain build has no Tailwind to establish the layer order, so it states
// it, in the order Tailwind uses: theme, base, components.
const tokensCss = `${HEADER}
@layer theme, base, components;

${layered(`:root {\n${[...themed, ...plain].join("\n")}\n}`, toneVars)}

${toneSurface}
`;

// Tone utilities for Tailwind sites: bg-tone, text-on-tone,
// text-on-tone-muted, text-tone-accent, bg-tone-hover, border-tone-border,
// bg-tone-field… They are colours like any other, so every colour utility
// works with them (bg-on-tone and text-tone give the button flip).
//
// `inline` is required, not a preference. Without it Tailwind would define
// --color-tone once on :root, resolving var(--tone-bg) there — every element
// would get the page's tone. Inlined, each utility reads var(--tone-bg) on
// the element it is applied to, so it follows the nearest [data-tone].
const toneUtilities = [
  ["tone", "bg"],
  ["on-tone", "fg"],
  ["on-tone-muted", "fg-muted"],
  ["tone-accent", "accent"],
  ["tone-hover", "bg-hover"],
  ["tone-border", "border"],
  ["tone-border-strong", "border-strong"],
  ["tone-field", "field"],
  ["tone-focus", "focus"],
].map(([utility, variable]) => `  --color-${utility}: var(--tone-${variable});`);

// `static`: Tailwind otherwise drops theme variables no utility uses, and
// components.css reads these by name whether or not a site's own markup does.
// Tailwind emits this block into @layer theme itself.
const themeCss = `${HEADER}
@theme static {
${themed.join("\n")}
}

@theme inline {
${toneUtilities.join("\n")}
}

${layered(`:root {\n${plain.join("\n")}\n}`, toneVars)}

${toneSurface}
`;

// Buttons take a tone's surface and text colour as a pair, by name
// (data-variant), without becoming that tone themselves — see Button.tsx.
// Generated here so a new tone is a new button variant with no second edit.
const variantCss = `@layer components {\n${Object.entries(tones)
  .map(([name, t]) => `  :is(.ds-button, .ds-icon-button)[data-variant="${name}"] {\n    --ds-variant-bg: ${t.bg};\n    --ds-variant-fg: ${t.fg};\n  }`)
  .join("\n\n")}\n}`;

const componentsCss = `${HEADER}
${variantCss}

${readFileSync(join(ROOT, "css", "components.css"), "utf8").replace(/\r\n/g, "\n")}`;

const dist = join(ROOT, "dist");
mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, "tokens.css"), tokensCss);
writeFileSync(join(dist, "theme.css"), themeCss);
writeFileSync(join(dist, "components.css"), componentsCss);
copyFileSync(join(ROOT, "tokens", "tokens.json"), join(dist, "tokens.json"));
writeFileSync(join(dist, "tones.json"), JSON.stringify(tones, null, 2) + "\n");

console.log(`tokens: ${themed.length + plain.length} variables, ${Object.keys(tones).length} tones → dist/`);
